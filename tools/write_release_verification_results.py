#!/usr/bin/env python3
from pathlib import Path
import json,datetime
ROOT=Path(__file__).resolve().parents[1]
VERSION=(ROOT/'VERSION').read_text().strip()
cat=json.loads((ROOT/'verification/test-catalog.json').read_text())['tests']
auto=[t for t in cat if t.get('automated')]
now=datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)
stamp=now.strftime('%Y%m%dT%H%M%SZ')
run_id=f'release-{VERSION}-{stamp}'
obj={
  'schema_version':'1.0','run_id':run_id,'application_version':VERSION,
  'run_type':'release','environment':'release_build','source':'release_build',
  'started_at':now.isoformat().replace('+00:00','Z'),'completed_at':now.isoformat().replace('+00:00','Z'),
  'overall_status':'pass','note':'tools/run-tests.sh fullførte uten feil.',
  'results':[{'result_id':f'{run_id}-{t["test_id"].lower()}','test_id':t['test_id'],'result_status':'pass','observed_at':now.isoformat().replace('+00:00','Z'),'executor':'release_build','note':'Registrert etter komplett grønn releaseport.','evidence_ref':t.get('implementation_ref')} for t in auto]
}
(ROOT/'verification/release-results.json').write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
def q(v):
 if v is None:return 'NULL'
 return "'"+str(v).replace("'","''")+"'"
def dt(v):return q(v.replace('T',' ').replace('Z',''))
lines=['-- Generated by tools/write_release_verification_results.py after a successful release gate.','SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;']
lines.append("INSERT INTO verification_test_runs(run_id,application_version,run_type,environment,source,started_at,completed_at,overall_status,operation_id,note,created_at) VALUES (%s,%s,'release','release_build','release_build',%s,%s,'pass',NULL,%s,%s);"%(q(run_id),q(VERSION),dt(obj['started_at']),dt(obj['completed_at']),q(obj['note']),dt(obj['completed_at'])))
for r in obj['results']:
 lines.append("INSERT INTO verification_test_results(result_id,run_id,test_id,result_status,observed_at,executor,note,evidence_ref,created_at) VALUES (%s,%s,%s,'pass',%s,'release_build',%s,%s,%s);"%(q(r['result_id']),q(run_id),q(r['test_id']),dt(r['observed_at']),q(r['note']),q(r['evidence_ref']),dt(r['observed_at'])))
(ROOT/'sql/25-release-verification-results-seed.sql').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Wrote structured PASS results for {len(auto)} automated tests: {run_id}')

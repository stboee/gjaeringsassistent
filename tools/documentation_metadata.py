"""Documentation source synchronization and derived interface inspection.

No runtime code, installed SQL or domain facts are generated by this module.
"""
from pathlib import Path
import hashlib
import json
import re
from system_metadata import insert_rows


def sync_document_sources(root):
    root = Path(root)
    policy = json.loads((root/'docs/sources/document-policy.json').read_text())
    block = (root/policy['guardrail_source']).read_text().strip()
    pattern = r'<!-- BEGIN ARCHITECTURE GUARDRAILS -->.*?<!-- END ARCHITECTURE GUARDRAILS -->'
    for name in policy['guardrail_targets']:
        p = root/name
        text = p.read_text()
        if re.search(pattern, text, re.S):
            text = re.sub(pattern, lambda _: block, text, flags=re.S)
        else:
            title = re.search(r'^# .+$', text, re.M)
            if not title:
                raise ValueError('No document title: '+name)
            text = text[:title.end()]+'\n\n'+block+text[title.end():]
        p.write_text(text)
    rows = ['| Gruppe | Dokument | Rolle |', '|---|---|---|']
    for group in policy['groups']:
        for name in group['documents']:
            text = (root/'docs'/name).read_text()
            title = re.search(r'^# (.+)$', text, re.M)[1]
            role = re.search(r'^role:\s*(.+)$', text, re.M)[1]
            rows.append(f'| {group["title"]} | [{title}]({name}) | {role} |')
    p = root/'docs/00-DOKUMENTKART-OG-STATUS.md'
    text = re.sub(r'<!-- BEGIN DOCUMENT MAP -->.*?<!-- END DOCUMENT MAP -->',
                  lambda _: '<!-- BEGIN DOCUMENT MAP -->\n'+'\n'.join(rows)+'\n<!-- END DOCUMENT MAP -->',
                  p.read_text(), flags=re.S)
    p.write_text(text)


def routine_definitions(root):
    definitions = {}
    for name in ['sql/11-runtime-routines.sql', 'sql/12-operator-routines.sql']:
        sql = (Path(root)/name).read_text()
        for match in re.finditer(r'CREATE\s+PROCEDURE\s+(\w+)\s*\(', sql, re.I):
            start = match.end()
            pos, depth = start, 1
            while depth:
                if sql[pos] == '(':
                    depth += 1
                elif sql[pos] == ')':
                    depth -= 1
                pos += 1
            definitions[match[1]] = {'source': name,
                'declaration': ' '.join(sql[start:pos-1].split())}
    return definitions


def interface_reference(root):
    root = Path(root)
    catalog = json.loads((root/'contracts/interface-catalog.json').read_text())
    flow = json.loads((root/'nodered/flows.template.json').read_text())
    routines = routine_definitions(root)
    calls = {}
    for node in flow:
        for routine in set(re.findall(r'\bCALL\s+(ga_\w+)\s*\(', node.get('func', ''), re.I)):
            calls.setdefault(routine, []).append(node['id'])
    ha = next(i for i in catalog['interfaces'] if i['interface_id']=='IF-NR-HA')
    registries = {name: insert_rows(root/'sql/21-system-metadata-seed.sql', name)
                  for name in ha['registries']}
    names = sorted({p for i in catalog['interfaces']
                    for kind in ['authority', 'derived_or_captured', 'implementation', 'checks']
                    for p in i[kind]})
    return {'schema_version': '1.0', 'generated_from': 'contracts/interface-catalog.json + SQL registries/routines + physical flow',
            'authority': 'Inspection only; owners remain the catalogued sources. No target-HA verification claim.',
            'interfaces': catalog['interfaces'], 'db_routines': routines,
            'node_red_routine_calls': {k: sorted(v) for k,v in sorted(calls.items())},
            'ha_registries': registries,
            'source_fingerprints': {p: hashlib.sha256((root/p).read_bytes()).hexdigest() for p in names}}


def build_interface_reference(root):
    root = Path(root)
    data = interface_reference(root)
    out = root/'docs/generated'
    out.mkdir(exist_ok=True)
    (out/'interface-reference.json').write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n')
    lines = ['# Grensesnitt – generert referanse', '',
             '> Avledet inspeksjon av faktiske SQL-registre, rutiner og flow. Se den vedlikeholdte [kildekatalogen](../../contracts/interface-catalog.json). Ingen målmiljøtest hevdes.', '',
             '## Eierskap og kontroll', '', '| Grense | Autoritative kilder | Kontroller |', '|---|---|---|']
    def links(names):
        return '<br>'.join(f'[{p}](../../{p})' for p in names)
    for item in data['interfaces']:
        lines.append(f'| {item["name"]} | {links(item["authority"])} | {links(item["checks"])} |')
    lines += ['', '## MariaDB-rutiner og faktiske Node-RED-kall', '',
              '| Rutine | Parameterdeklarasjon fra SQL | Kilde | Kallende noder |', '|---|---|---|---|']
    for name, info in sorted(data['db_routines'].items()):
        callers = ', '.join(data['node_red_routine_calls'].get(name, [])) or 'Ingen direkte CALL i flow; se SQL-/adapterkonsument'
        lines.append(f'| `{name}` | `{info["declaration"] or "ingen"}` | [{info["source"]}](../../{info["source"]}) | {callers} |')
    lines += ['', '## HA-registre', '', '| Register | Rader | Eier |', '|---|---:|---|']
    for name, rows in data['ha_registries'].items():
        lines.append(f'| `{name}` | {len(rows)} | SQL/installerte MariaDB-registre |')
    lines += ['', 'Feltstier, datatyper, required/absence-policy, inputbindinger, mapping og fysiske ruter er med i [JSON-uttrekket](interface-reference.json).', '',
              '## Read-model-publisering', '', '| Produsent | Staging | Argumentnode | Exec | Resultat / stderr |', '|---|---|---|---|---|']
    pub = next(i for i in data['interfaces'] if i['interface_id']=='IF-NR-PUBLICATION')
    for p in pub['pipelines']:
        lines.append('| '+' | '.join('`'+p[k]+'`' for k in ['producer','staging','arguments','executor'])+f' | `{p["success"]}` / `{p["stderr"]}` |')
    lines += ['', 'Jobbens obligatoriske felt er stage_path og target_path. diagnostics_level kan være summary/full. source_path er ikke et alternativt feltnavn. Se [maskinskjema](../../contracts/publication-job.schema.json). Kildene og de faktiske koblingene prøves av verify-interface-contracts.py; faktiske argumenter, shell, JSON/gzip og feil prøves av test-interface-contracts.js og test-p24r8.js.', '']
    (out/'interface-reference.md').write_text('\n'.join(lines))


def build_requirement_history(root):
    root=Path(root)
    data=json.loads((root/'docs/sources/requirements-history.json').read_text())
    lines=['# Krav- og beslutningshistorikk – generert leseutgave','',
           '> Avledet fra [den ene vedlikeholdte historikkilden](../sources/requirements-history.json). Baseline er dokumentert tekst ved angitt commit, ikke en påstått original dialogdato. Gjeldende krav/beslutninger finnes i sine faglige dokumenter.','']
    def cell(value):
        return str(value).replace('|','\\|').replace('\n',' ')
    for event in data['events']:
        lines+=['## '+event['event_id']+' – '+event['kind'],'',
                'Registrert: '+event['recorded_on']+'. Kildetype: '+event['source_kind']+'.','']
        if event.get('note'):lines += [event['note'],'']
        if event.get('source_locator'):lines += ['Kildeplassering: '+event['source_locator'],'']
        for statement in event.get('statements',[]):lines.append('- '+statement)
        for statement in event.get('reported_user_statements',[]):
            lines.append('- Rapportert dato '+statement['reported_at_utc']+': '+statement['summary'])
        if event.get('requirements'):
            lines += ['','### Krav ved baseline','','| ID | Status | Dokumentert krav | Opprinnelig kildeposisjon |','|---|---|---|---|']
            for r in event['requirements']:
                url=f'https://github.com/stboee/gjaeringsassistent/blob/{event["source_commit"]}/docs/{r["source"]}#L{r["line"]}'
                lines.append(f'| {r["id"]} | {cell(r["status"])} | {cell(r["requirement"])} | [kilde]({url}) |')
        if event.get('decisions'):
            lines += ['','### Beslutninger ved baseline','','| ID | Beslutning | Begrunnelse | Konsekvens |','|---|---|---|---|']
            for d in event['decisions']:
                lines.append('| '+' | '.join(cell(d[k]) for k in ['id','decision','rationale','consequence'])+' |')
        lines.append('')
    (root/'docs/generated/requirements-history.md').write_text('\n'.join(lines))

#!/usr/bin/env python3
from pathlib import Path
import json,re,sys
ROOT=Path(__file__).resolve().parents[1]
DOCS=ROOT/'docs'
GEN=DOCS/'generated'
VER=ROOT/'verification'
SQL=ROOT/'sql/24-verification-metadata-seed.sql'

def q(v):
    if v is None: return 'NULL'
    return "'"+str(v).replace("'","''")+"'"

def req_rows():
    out=[]; seen=set(); order=0
    for p in sorted(DOCS.glob('0[1-4]-*.md')):
        text=p.read_text(encoding='utf-8')
        doc=re.search(r'^doc_id:\s*(\S+)',text,re.M)
        doc_id=doc.group(1) if doc else p.stem
        for ln,line in enumerate(text.splitlines(),1):
            m=re.match(r'^\|\s*(REQ-[A-Z]+-\d+)\s*\|\s*([^|]+)\|\s*(.*?)\s*\|\s*$',line)
            if not m: continue
            rid,status,statement=m.groups()
            if rid in seen: raise SystemExit(f'duplicate requirement {rid}')
            seen.add(rid); order+=1
            cls=rid.split('-')[1].lower()
            out.append(dict(requirement_id=rid,document_id=doc_id,requirement_class=cls,status='active',statement=statement.strip(),source_ref=f'{p.name}:{ln}',sort_order=order))
    return out

def decisions():
    p=DOCS/'14-AKTIVE-BESLUTNINGER.md'; out=[]
    for ln,line in enumerate(p.read_text(encoding='utf-8').splitlines(),1):
        if not re.match(r'^\|\s*(?:DEC|ADR)-[A-Z0-9-]+\s*\|',line): continue
        c=[x.strip() for x in line.strip().strip('|').split('|')]
        if len(c)>=4: out.append(dict(decision_id=c[0],decision=c[1],rationale=c[2],consequence=c[3],status='active',source_ref=f'{p.name}:{ln}'))
    return out

reqs=req_rows(); decs=decisions()
tests=json.loads((VER/'test-catalog.json').read_text(encoding='utf-8'))['tests']
model=json.loads((VER/'verification-model.json').read_text(encoding='utf-8'))
req_ids={x['requirement_id'] for x in reqs}; dec_ids={x['decision_id'] for x in decs}; test_ids={x['test_id'] for x in tests}
if len(test_ids)!=len(tests): raise SystemExit('duplicate test_id')
ver_ids=set()
for v in model['verifications']:
    if v['verification_id'] in ver_ids: raise SystemExit('duplicate verification_id '+v['verification_id'])
    ver_ids.add(v['verification_id'])
    missing=set(v.get('requirements',[]))-req_ids
    if missing: raise SystemExit(f"{v['verification_id']} unknown requirements {sorted(missing)}")
    missing=set(v.get('tests',[]))-test_ids
    if missing: raise SystemExit(f"{v['verification_id']} unknown tests {sorted(missing)}")
for link in model.get('decision_requirement_links',[]):
    if link['decision_id'] not in dec_ids: raise SystemExit('unknown decision '+link['decision_id'])
    missing=set(link['requirements'])-req_ids
    if missing: raise SystemExit(f"{link['decision_id']} unknown requirements {sorted(missing)}")
for tid,steps in model.get('uat_steps',{}).items():
    if tid not in test_ids: raise SystemExit('unknown UAT test '+tid)

lines=["-- Generated by tools/build_verification_registry.py; do not edit by hand.","SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;","SET SESSION sql_mode = 'STRICT_TRANS_TABLES,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION';",""]
# The unique presentation order is not an identity. Park existing orders above
# both ranges before upserting by stable ID; otherwise a new ID can match the
# wrong row through the secondary unique key. Publish the metadata atomically.
lines += ["START TRANSACTION;",
          f"SET @ga_requirement_sort_offset=(SELECT COALESCE(MAX(sort_order),0)+{len(reqs)+1} FROM verification_requirements_catalog);",
          "UPDATE verification_requirements_catalog SET sort_order=sort_order+@ga_requirement_sort_offset ORDER BY sort_order DESC;",
          f"SET @ga_test_sort_offset=(SELECT COALESCE(MAX(sort_order),0)+{len(tests)+1} FROM verification_tests);",
          "UPDATE verification_tests SET sort_order=sort_order+@ga_test_sort_offset ORDER BY sort_order DESC;"]
for r in reqs:
    lines.append("INSERT INTO verification_requirements_catalog(requirement_id,document_id,requirement_class,status,statement,source_ref,sort_order,created_at) VALUES (%s,%s,%s,%s,%s,%s,%s,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE document_id=VALUES(document_id),requirement_class=VALUES(requirement_class),status=VALUES(status),statement=VALUES(statement),source_ref=VALUES(source_ref),sort_order=VALUES(sort_order);"%(q(r['requirement_id']),q(r['document_id']),q(r['requirement_class']),q(r['status']),q(r['statement']),q(r['source_ref']),r['sort_order']))
for d in decs:
    lines.append("INSERT INTO verification_decisions_catalog(decision_id,decision,rationale,consequence,status,source_ref,created_at) VALUES (%s,%s,%s,%s,%s,%s,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE decision=VALUES(decision),rationale=VALUES(rationale),consequence=VALUES(consequence),status=VALUES(status),source_ref=VALUES(source_ref);"%(q(d['decision_id']),q(d['decision']),q(d['rationale']),q(d['consequence']),q(d['status']),q(d['source_ref'])))
for i,v in enumerate(model['verifications'],1):
    lines.append("INSERT INTO verification_definitions(verification_id,verification_type,title,acceptance_criterion,status,created_at) VALUES (%s,%s,%s,%s,'active',UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE verification_type=VALUES(verification_type),title=VALUES(title),acceptance_criterion=VALUES(acceptance_criterion),status=VALUES(status);"%(q(v['verification_id']),q(v['verification_type']),q(v['title']),q(v['acceptance_criterion'])))
    for rid in v.get('requirements',[]):
        lines.append("INSERT INTO verification_requirement_links(requirement_id,verification_id,required,created_at) VALUES (%s,%s,1,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE required=VALUES(required);"%(q(rid),q(v['verification_id'])))
for i,t in enumerate(tests,1):
    lines.append("INSERT INTO verification_tests(test_id,test_type,title,description,method_type,implementation_ref,automated,status,sort_order,created_at) VALUES (%s,%s,%s,%s,%s,%s,%d,'active',%d,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE test_type=VALUES(test_type),title=VALUES(title),description=VALUES(description),method_type=VALUES(method_type),implementation_ref=VALUES(implementation_ref),automated=VALUES(automated),status=VALUES(status),sort_order=VALUES(sort_order);"%(q(t['test_id']),q(t['test_type']),q(t['title']),q(t['description']),q(t['method_type']),q(t.get('implementation_ref')),1 if t['automated'] else 0,i))
for v in model['verifications']:
    for tid in v.get('tests',[]):
        lines.append("INSERT INTO verification_test_links(verification_id,test_id,required,created_at) VALUES (%s,%s,1,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE required=VALUES(required);"%(q(v['verification_id']),q(tid)))
for link in model.get('decision_requirement_links',[]):
    for rid in link['requirements']:
        lines.append("INSERT INTO verification_decision_requirement_links(decision_id,requirement_id,created_at) VALUES (%s,%s,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE created_at=created_at;"%(q(link['decision_id']),q(rid)))
for tid,steps in model.get('uat_steps',{}).items():
    for st in steps:
        lines.append("INSERT INTO verification_uat_steps(test_id,step_order,instruction,expected_result,created_at) VALUES (%s,%d,%s,%s,UTC_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE instruction=VALUES(instruction),expected_result=VALUES(expected_result);"%(q(tid),st['step_order'],q(st['instruction']),q(st['expected_result'])))
lines.append('COMMIT;')
if '--no-sql' not in sys.argv:
    SQL.write_text('\n'.join(lines)+'\n',encoding='utf-8')
summary={'schema_version':'1.0','requirements_count':len(reqs),'decisions_count':len(decs),'verification_count':len(model['verifications']),'tests_count':len(tests),'test_types':{k:sum(1 for t in tests if t['test_type']==k) for k in ['TECH','FUNC','UAT']},'requirements':reqs,'decisions':decs,'verifications':model['verifications'],'tests':tests,'decision_requirement_links':model.get('decision_requirement_links',[]),'uat_steps':model.get('uat_steps',{})}
(GEN/'verification-model.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f"Generated verification metadata (SQL written: {'--no-sql' not in sys.argv}): {len(reqs)} requirements, {len(decs)} decisions, {len(model['verifications'])} verifications, {len(tests)} tests")
